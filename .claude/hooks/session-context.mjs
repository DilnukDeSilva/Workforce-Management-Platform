#!/usr/bin/env node
// SessionStart(startup|resume|clear|compact): inject live lifecycle state so every session —
// including after context compaction — starts knowing the work item, phase, gates and next action.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT, currentBranch, derivePhase, enforcementEnabled, git, listSlugs, loadState, parseBranch, summarize } from '../../scripts/aidlc/lib.mjs';

try {
  const branch = currentBranch();
  const parsed = parseBranch(branch);
  const out = ['# AI-DLC session context (auto-generated by .claude/hooks/session-context.mjs)', ''];
  out.push(`Branch: ${branch || 'unknown'}${enforcementEnabled() ? '' : '  — ⚠ AIDLC_ENFORCE=off: guardrails relaxed for this session'}`);

  const state = parsed && loadState(parsed.slug);
  if (state) {
    out.push('', 'Active work item:', summarize(state));
    out.push('', `Artifacts: docs/features/${state.slug}/ — read journal.md for decisions and blockers before continuing.`);
  } else {
    const open = listSlugs().map((s) => loadState(s)).filter((s) => derivePhase(s) !== 'done');
    out.push('', parsed ? `No work item for this branch yet (expected docs/features/${parsed.slug}/).` : 'Not on a work-item branch — production code edits are blocked until one is started.');
    if (open.length) out.push('Open work items: ' + open.map((s) => `${s.slug} [${derivePhase(s)}] on ${s.branch}`).join('; '));
    out.push('To begin: /inception <feature request>, /fix <bug>, or `npm run aidlc -- start chore <slug> --title "..."`.');
  }

  const dirty = git(['status', '--porcelain']).split('\n').filter(Boolean);
  if (dirty.length) out.push('', `Uncommitted changes: ${dirty.length} path(s) — the user commits; never run git commit/push.`);

  const lessons = join(REPO_ROOT, 'docs/aidlc/lessons.md');
  if (existsSync(lessons)) {
    const items = readFileSync(lessons, 'utf8').split('\n').filter((l) => /^- \*\*/.test(l)).slice(-5);
    if (items.length) out.push('', 'Recent lessons (docs/aidlc/lessons.md):', ...items);
  }
  process.stdout.write(out.join('\n') + '\n');
} catch (e) {
  process.stderr.write(`[aidlc session-context] ${e?.stack || e}\n`);
}
process.exit(0);
